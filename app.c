#include "connection.h"

int main()
{
    SetupConsole();
    showLogo();
    void* connect = NULL;
    printf("\n\n\n \tConnecting to discord pipe...\n");
    setbuf(stdout, NULL);
    setbuf(stderr, NULL);
    connect = EstablishConnection();
    if (connect == NULL) {
        RestoreConsole(); 
        return EXIT_FAILURE;
    }
    run(connect);
    RestoreConsole();
    getchar();
    return EXIT_SUCCESS;
}

